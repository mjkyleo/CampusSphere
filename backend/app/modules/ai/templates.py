def pick_greeting_template(
    *, mood: str = "", focus: str = "", period: str = "morning", seed: int = 0
) -> tuple[str, str]:
    """按种子选取一条问候模板，返回 ``(text, emoji)``。

    ``seed`` 由「用户 + 日期 + focus + 第几次生成」派生，保证同一天不同操作、
    或不同天的同一操作，都能拿到不同的句子。
    """
    key = mood if mood in _GREETING_TEMPLATES else "generic"
    pool = _GREETING_TEMPLATES[key]
    # focus 参与偏移：同样状态下换重点也能换句子
    offset = stable_hash(f"{focus}:{seed}")
    text = pool[offset % len(pool)]
    period_label = PERIODS.get(period, "今天")
    text = text.replace("{p}", period_label)
    return text, PERIOD_EMOJI.get(period, "✨")


def stable_hash(value: str) -> int:
    """稳定哈希（不依赖 PYTHONHASHSEED，保证重启后结果一致）。"""
    import zlib

    return zlib.crc32(value.encode("utf-8"))


def sanitize_text(text: str, max_len: int = 60) -> str:
    """清洗模型输出：去控制字符、折叠空白、硬截断。"""
    cleaned = "".join(ch if ch.isprintable() else " " for ch in (text or ""))
    cleaned = " ".join(cleaned.split())
    return cleaned[:max_len]
